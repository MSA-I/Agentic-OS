// Generates src/lib/executionFrozenSurfaces.ts: for every page route, which frozen
// execution paths its component tree calls. The UI uses it to tell the truth about
// disabled actions before the user clicks one.
//
//   node scripts/control-plane/generate-frozen-surfaces.mjs           # write
//   node scripts/control-plane/generate-frozen-surfaces.mjs --check   # fail if stale
//
// Inputs are the freeze manifest and the mutation inventory, so this file cannot
// claim a frozen surface the control plane does not actually freeze.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const repositoryRoot = path.resolve(import.meta.dirname, "..", "..");
const sourceRoot = path.join(repositoryRoot, "src");
const appRoot = path.join(sourceRoot, "app");
const outputPath = path.join(sourceRoot, "lib", "executionFrozenSurfaces.ts");
const checkOnly = process.argv.includes("--check");

const manifestSource = readFileSync(
  path.join(sourceRoot, "lib", "control-plane", "frozenExecutionRoutes.ts"),
  "utf8",
);
const frozenPaths = new Set(
  [...manifestSource.matchAll(/^ {2}"(?:POST|PUT|PATCH|DELETE) (\/api\/[^"]+)",$/gmu)].map((match) => match[1]),
);
if (frozenPaths.size === 0) throw new Error("freeze manifest produced no paths");

const inventory = JSON.parse(
  readFileSync(path.join(repositoryRoot, "docs", "control-plane", "mutation-inventory.json"), "utf8"),
);

// file (repo-relative, posix) -> frozen API paths it mutates
const frozenCallsByFile = new Map();
for (const caller of inventory.frontendCallers ?? []) {
  if (!frozenPaths.has(caller.apiPath)) continue;
  const list = frozenCallsByFile.get(caller.file) ?? new Set();
  list.add(caller.apiPath);
  frozenCallsByFile.set(caller.file, list);
}

// Components mounted on every page by the shell. Their frozen calls are not a
// property of any one route, so they are disabled in the component itself
// instead of being reported as that route's surface.
const GLOBAL_COMPONENTS = new Set([
  "src/components/SetupCenterHost.tsx",
  "src/components/CommandPalette.tsx",
]);

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(absolute) : [absolute];
  });
}

function toRelative(absolute) {
  return path.relative(repositoryRoot, absolute).split(path.sep).join("/");
}

function resolveImport(specifier, fromFile) {
  let base;
  if (specifier.startsWith("@/")) base = path.join(sourceRoot, specifier.slice(2));
  else if (specifier.startsWith(".")) base = path.resolve(path.dirname(fromFile), specifier);
  else return null;
  for (const candidate of [
    `${base}.tsx`,
    `${base}.ts`,
    path.join(base, "index.tsx"),
    path.join(base, "index.ts"),
    base,
  ]) {
    if (!/\.tsx?$/u.test(candidate)) continue;
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}

const IMPORT_SPECIFIER = /(?:import|export)[\s\S]*?from\s*["']([^"']+)["']|import\s*\(\s*["']([^"']+)["']\s*\)/gu;

/** Every frozen path reachable from one page through local imports. */
function frozenPathsForPage(pageFile) {
  const seen = new Set();
  const queue = [pageFile];
  const found = new Set();
  while (queue.length > 0) {
    const current = queue.pop();
    const relative = toRelative(current);
    if (seen.has(relative) || GLOBAL_COMPONENTS.has(relative)) continue;
    seen.add(relative);
    for (const apiPath of frozenCallsByFile.get(relative) ?? []) found.add(apiPath);
    const text = readFileSync(current, "utf8");
    for (const match of text.matchAll(IMPORT_SPECIFIER)) {
      const specifier = match[1] ?? match[2];
      if (!specifier) continue;
      const resolved = resolveImport(specifier, current);
      if (resolved) queue.push(resolved);
    }
  }
  return [...found].sort();
}

const surfaces = [];
for (const file of walk(appRoot)) {
  if (path.basename(file) !== "page.tsx") continue;
  const relativeDirectory = path.relative(appRoot, path.dirname(file));
  const route = relativeDirectory ? `/${relativeDirectory.split(path.sep).join("/")}` : "/";
  const paths = frozenPathsForPage(file);
  if (paths.length > 0) surfaces.push({ route, paths });
}
surfaces.sort((left, right) => left.route.localeCompare(right.route));

const lines = [
  "// GENERATED by scripts/control-plane/generate-frozen-surfaces.mjs — do not edit.",
  "// Route -> the frozen execution paths that route's components mutate. Regenerate",
  "// after any change to the freeze manifest or to a component's mutation calls:",
  "//   npm run control-plane:frozen-surfaces",
  "",
  "export const FROZEN_EXECUTION_SURFACES: Readonly<Record<string, readonly string[]>> = {",
  ...surfaces.map(({ route, paths }) => `  "${route}": [${paths.map((item) => `"${item}"`).join(", ")}],`),
  "};",
  "",
  "export function frozenPathsForRoute(pathname: string): readonly string[] {",
  "  return FROZEN_EXECUTION_SURFACES[pathname] ?? [];",
  "}",
  "",
];
const content = lines.join("\n");

if (checkOnly) {
  const existing = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (existing !== content) {
    process.stderr.write(`frozen surfaces are stale: ${toRelative(outputPath)}\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write(`verified ${toRelative(outputPath)} (${surfaces.length} routes)\n`);
  }
} else {
  writeFileSync(outputPath, Buffer.from(content, "utf8"));
  process.stdout.write(`wrote ${toRelative(outputPath)} (${surfaces.length} routes)\n`);
}
